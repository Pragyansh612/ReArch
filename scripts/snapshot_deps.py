"""Write config/dependency_snapshot.yaml: the latest STABLE version of every dependency coordinate.

Run once (and again when you want a fresher table); commit the result. The analyzer reads only the snapshot,
so analysis stays offline and deterministic. Source: Maven Central maven-metadata.xml.

    python scripts/snapshot_deps.py [--files FILE ...] [--out config/dependency_snapshot.yaml]

"Stable" = not alpha/beta/rc/milestone/snapshot/preview/dev/ea/cr. "Latest" = highest by numeric version parts.
"""

from __future__ import annotations

import argparse
import datetime
import re
import sys
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from analyzer.deps import parse_pom, parse_version_catalog

CENTRAL = "https://repo1.maven.org/maven2"
UNSTABLE = re.compile(r"(?i)(alpha|beta|[-.]rc\d*|[-.]m\d+|milestone|snapshot|preview|[-.]dev|[-.]ea\b|[-.]cr\d*|"
                      r"incubat|nightly|[-.]b\d+$|\.pr\d+)")
DEFAULT_FILES = [
    "targets/ofbiz-framework/gradle/libs.versions.toml",
    "targets/jpetstore-6/pom.xml",
    "fixtures/legacy-sample/pom.xml",
    "fixtures/legacy-sample/gradle/libs.versions.toml",
]


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(n) for n in re.findall(r"\d+", version))


def latest_stable(coordinate: str) -> str | None:
    group, artifact = coordinate.split(":")
    url = f"{CENTRAL}/{group.replace('.', '/')}/{artifact}/maven-metadata.xml"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "rearch-snapshot/0.1"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            root = ET.fromstring(resp.read())
    except (urllib.error.URLError, ET.ParseError, TimeoutError):
        return None
    versions = [v.text for v in root.iter("version") if v.text and not UNSTABLE.search(v.text)]
    return max(versions, key=version_key) if versions else None


def coordinates(files: list[Path]) -> list[str]:
    found: set[str] = set()
    for f in files:
        declared = parse_pom(f) if f.name == "pom.xml" else parse_version_catalog(f)
        found.update(c for c, _ in declared)
    return sorted(found)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--files", nargs="*", default=DEFAULT_FILES)
    ap.add_argument("--out", default=str(ROOT / "config/dependency_snapshot.yaml"))
    args = ap.parse_args()
    renames = yaml.safe_load((ROOT / "config/dependency_renames.yaml").read_text())["renames"]
    coords = sorted(set(coordinates([ROOT / f for f in args.files])) | set(renames))
    entries: dict[str, dict[str, object]] = {}
    for i, coord in enumerate(coords, 1):
        latest = latest_stable(coord)
        entries[coord] = {"latest_stable_version": latest,
                          "latest_major": version_key(latest)[0] if latest else None}
        if coord in renames:
            entries[coord]["superseded_by"] = renames[coord]
        print(f"[{i}/{len(coords)}] {coord} -> {latest}", flush=True)
        time.sleep(0.05)
    doc = {"as_of": datetime.date.today().isoformat(), "source": "Maven Central maven-metadata.xml (repo1.maven.org)",
           "entries": entries}
    header = ("# GENERATED by scripts/snapshot_deps.py -- do not edit by hand. Committed so analysis is offline and\n"
              "# deterministic. Re-run the script to refresh; entries with null versions were not found on Central.\n")
    Path(args.out).write_text(header + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    missing = [c for c, e in entries.items() if e["latest_stable_version"] is None]
    print(f"wrote {args.out}: {len(entries)} coordinates, {len(missing)} unresolved {missing}")


if __name__ == "__main__":
    main()
